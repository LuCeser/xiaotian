// wordlistUserPrompt is the per-image user turn (same shape as the student
// pipeline: the system prompt carries the contract, this keeps the vision
// turn's two content parts). The subject rides the system prompt; the user
// turn names the same subject so the two content parts cannot disagree.
func wordlistUserPrompt(category string) string {
	if category == CategoryChinese {
		// Issue #11/#13: the Chinese turn names the mixed-page job — 词语
		//表 entries AND whole poems AND whole passages AND the
		// display-only other blocks — so the two content parts cannot
		// disagree about the contract.
		return `请按词语表条目、完整古诗、完整课文和其他内容块分类提取这张照片，并读取教材信息。`
	}
	return `请提取这张照片里的英语词表条目和教材信息。`
}

// Category values the word-list pipeline understands (Issue #10). The
// literals match the vocabulary category enum (D-06: "english"|"chinese").
const (
	CategoryEnglish = "english"
	CategoryChinese = "chinese"
)

// maxWordlistEntries caps one recognition at the add path's per-request
// entry cap (100, pkg/web/api maxEntries): a photo whose recognized list
// exceeds it cannot be committed in one request anyway, and a runaway model
// reply must not materialize an unbounded slice.
const maxWordlistEntries = 100

// maxWordlistPoems caps the poems array of one mixed-page recognition
// (Issue #11): a 语文 photo page cannot carry more than a handful of whole
// poems; the cap bounds a runaway reply the same way maxWordlistEntries
// bounds entries, and it matches the commit path's per-request poem cap
// (pkg/web/api maxPoems).
const maxWordlistPoems = 20

// maxWordlistPassages caps the passages array of one mixed-page
// recognition (Issue #13): a photo page carries at most a couple of whole
// passages; the cap bounds a runaway reply the same way maxWordlistPoems
// bounds poems, and it matches the commit path's per-request cap
// (pkg/web/api maxPassages).
const maxWordlistPassages = 10

// maxPoemLines / maxPoemLineRunes bound ONE poem (Issue #11): 古诗按整首
// 保存 and no 长诗选段 exists, so a primary-school poem is a few short
// lines; anything past these caps is a misparsed reply, not a poem.
const (
	maxPoemLines     = 64
	maxPoemLineRunes = 200
)

// maxPassageParagraphs / maxPassageParagraphRunes bound ONE passage
// (Issue #13): a primary-school 课文 is a few dozen 自然段 of prose;
// anything past these caps is a misparsed reply, not a passage, and the
// commit path enforces the same bounds again (pkg/web/api
// maxPassageParagraphs / maxPassageParagraphRunes).
const (
	maxPassageParagraphs     = 60
	maxPassageParagraphRunes = 1000
)

// WordlistPipeline reads one word-list photo end-to-end: sniff PNG/JPEG,
// enforce the byte cap, call the vision seam, parse the reply into draft
// entries. It owns NO state — recognition results are a client-side draft
// until the parent explicitly commits them through the ordinary add path
// (nothing here touches any database).
type WordlistPipeline struct {
	read     ListReader
	maxBytes int
}

// NewWordlistPipeline builds the pipeline. maxBytes caps one upload (the
// caller passes the photo config's MaxImageBytes); inputs past the cap fail
// with ErrImageTooLarge before any API round trip. A nil ListReader yields
// a pipeline whose Recognize fails with the errNilSeam wiring error.
func NewWordlistPipeline(read ListReader, maxBytes int) *WordlistPipeline {
	return &WordlistPipeline{read: read, maxBytes: maxBytes}
}

// MaxBytes exposes the pipeline's upload byte cap so the HTTP layer can bound
// its request-body reads with the exact same limit (one source of truth —
// the api handler's MaxBytesReader and the pipeline check can never
// disagree).
func (p *WordlistPipeline) MaxBytes() int {
	return p.maxBytes
}

// Recognize converts one photo's bytes into the draft recognition result
// (textbook header + entries) for the given subject. category selects the
// extraction contract: CategoryChinese reads a 语文词语表 (multi-character
// 词语, pinyin/annotation into meaning, English content on the page
// ignored); CategoryEnglish — and any other value, the pre-Issue-#10
// default — reads an English word list. The MIME type is sniffed from the
// magic bytes (never trusting the declared Content-Type) and forwarded so
// the vision API decodes the right format. Error contract mirrors
// Pipeline.Process: sentinels are detectable via errors.Is. A photo with
// no recognizable word-list entries is a legal outcome — the caller shows
// "nothing recognized", not an error. Issue #47 adds the deterministic
// backstop on top of the contract: typographic decoration marks around
// word are trimmed for either subject, and under CategoryChinese an entry
// whose word carries no Han character — and, since Issue #13 gave the
// mis-selection a passage-shaped leak path, a passage whose title and
// paragraphs carry none — never reaches the draft.
func (p *WordlistPipeline) Recognize(ctx context.Context, image []byte, category string) (*WordlistResult, error) {
	if len(image) == 0 {
		return nil, ErrEmptyImage
	}
	mimeType, ok := sniffImage(image)
	if !ok {
		return nil, ErrNotImage
	}
	if p.maxBytes > 0 && len(image) > p.maxBytes {
		return nil, ErrImageTooLarge
	}
	if p.read == nil {
		return nil, errNilSeam
	}

	system := wordlistSystemPromptEnglish
	if category == CategoryChinese {
		system = wordlistSystemPromptChinese
	}
	reply, err := p.read(ctx, system, wordlistUserPrompt(category), image, mimeType)
	if err != nil {
		// Double-%w keeps both the sentinel and the upstream cause reachable
		// (same shape as Pipeline.Process).
		return nil, fmt.Errorf("%w: %w", errReaderFailed, err)
	}

	parsed, ok := parseWordlistReply(reply)
	if !ok {
		return nil, errUnparseableReply
	}
	if len(parsed.entries) > maxWordlistEntries {
		return nil, ErrTooManyEntries
	}
	// Issue #11: the mixed-page poem array obeys its own cap — a runaway
	// reply must not materialize an unbounded slice (same guard shape as
	// the entries cap above).
	if len(parsed.poems) > maxWordlistPoems {
		return nil, ErrTooManyPoems
	}
	// Issue #13: the passages array obeys its own cap for the same reason.
	if len(parsed.passages) > maxWordlistPassages {
		return nil, ErrTooManyPassages
	}

	var meta *WordlistTextbook
	if parsed.textbook != nil {
		trimmed := WordlistTextbook{
			Edition: strings.TrimSpace(parsed.textbook.Edition),
			Stage:   strings.TrimSpace(parsed.textbook.Stage),
			Grade:   strings.TrimSpace(parsed.textbook.Grade),
			Volume:  strings.TrimSpace(parsed.textbook.Volume),
			Module:  strings.TrimSpace(parsed.textbook.Module),
			Lesson:  strings.TrimSpace(parsed.textbook.Lesson),
		}
		if trimmed != (WordlistTextbook{}) {
			meta = &trimmed
		}
	}

	out := make([]WordlistEntry, 0, len(parsed.entries))
	for _, e := range parsed.entries {
		// Issue #47: word is the LANGUAGE unit only — the typographic marks
		// a printed list sets around its words (★ key-word stars, ※,
		// bullets…) are trimmed off both ends together with the whitespace
		// interleaving them ("★ library " → "library"); a mark-only word
		// ("★★") collapses into the empty-word case below.
		word := trimWordDecorations(e.Word)
		if word == "" {
			continue
		}
		// Issue #47's isolation backstop: the 语文 contract admits only
		// Han-carrying words into entries. A word with NO Han character is
		// English leaking through a mis-selected category (or stray
		// symbols) and is DROPPED, not re-shaped into others: OtherDraft
		// is a display-block contract (kind text=课文正文 / exercise,
		// summary a one-sentence block description) that an English word
		// fits neither, and the pipeline's precedent for a miscontracted
		// draft (empty word, untitled poem) is to drop it. The tightened
		// prompt keeps the model summarizing English content in others
		// itself — visible feedback stays the model's job, the guard
		// stays dumb and deterministic.
		if category == CategoryChinese && !containsHan(word) {
			continue
		}
		lesson := strings.TrimSpace(e.Lesson)
		if lesson == "" && meta != nil {
			// No own lesson → the page-level lesson governs (one photo is
			// usually one lesson's list; the parent can still re-assign per
			// row in the preview).
			lesson = meta.Lesson
		}
		out = append(out, WordlistEntry{
			Word:       word,
			Meaning:    strings.TrimSpace(e.Meaning),
			Lesson:     lesson,
			Confidence: clamp01(e.Confidence),
		})
	}
	passages := trimPassageDrafts(parsed.passages, meta)
	if category == CategoryChinese {
		// Issue #47's isolation backstop, covering the Issue #13 passage
		// path: an English page's running text is exactly what a passage
		// shape fits, so a passage whose title AND paragraphs carry no Han
		// character is English prose leaking through the same mis-selected
		// category as a Han-less entry word, and gets the same disposition
		// (dropped, not re-shaped into others).
		passages = dropNonHanPassages(passages)
	}
	return &WordlistResult{
		Textbook: meta,
		Entries:  out,
		Poems:    trimPoemDrafts(parsed.poems, meta),
		Passages: passages,
		Others:   trimOtherDrafts(parsed.others),
	}, nil
}

// trimPoemDrafts projects the decoded poems onto the draft contract
// (Recognize's poems-side twin of the entries loop): every field trimmed,
// confidence clamped, empty lines dropped, the poem's own missing lesson
// falling back to the page-level one. A poem with no title or no
// non-empty line is DROPPED — the parent confirms complete works only
// (古诗作为完整作品保存), and an untitled/empty shell is a misparse, not
// a poem to salvage. Lines past maxPoemLines are kept only up to the cap:
// a longer reply is a misparsed block (无长诗选段 — a whole primary-school
// poem is far shorter), and the commit path enforces the same bound again.
func trimPoemDrafts(poems []PoemDraft, meta *WordlistTextbook) []PoemDraft {
	out := make([]PoemDraft, 0, len(poems))
	for _, p := range poems {
		title := strings.TrimSpace(p.Title)
		if title == "" {
			continue
		}
		lines := make([]string, 0, len(p.Lines))
		for _, line := range p.Lines {
			line = strings.TrimSpace(line)
			if line != "" {
				lines = append(lines, line)
			}
			if len(lines) == maxPoemLines {
				break
			}
		}
		if len(lines) == 0 {
			continue
		}
		lesson := strings.TrimSpace(p.Lesson)
		if lesson == "" && meta != nil {
			lesson = strings.TrimSpace(meta.Lesson)
		}
		out = append(out, PoemDraft{
			Title:      title,
			Author:     strings.TrimSpace(p.Author),
			Lines:      lines,
			Lesson:     lesson,
			Required:   strings.TrimSpace(p.Required),
			Confidence: clamp01(p.Confidence),
		})
	}
	return out
}

// trimPassageDrafts projects the decoded passages onto the draft contract
// (Recognize's passages-side twin of trimPoemDrafts): every field trimmed,
// confidence clamped, empty paragraphs dropped, the passage's own missing
// lesson falling back to the page-level one. A passage with no title or
// no non-empty paragraph is DROPPED — the parent confirms complete
// originals only (课文按整篇原文保存), and an untitled/empty shell is a
// misparse, not a passage to salvage. Paragraphs past
// maxPassageParagraphs are kept only up to the cap; RequiredParagraphs
// keeps only the 1-based indexes that point at a KEPT paragraph, sorted
// and deduplicated — a mark the model numbered outside the real text
// (miscounted, 0-based) is noise, never a default-selection hint
// pointing at a paragraph that does not exist.
func trimPassageDrafts(passages []PassageDraft, meta *WordlistTextbook) []PassageDraft {
	out := make([]PassageDraft, 0, len(passages))
	for _, p := range passages {
		title := strings.TrimSpace(p.Title)
		if title == "" {
			continue
		}
		paragraphs := make([]string, 0, len(p.Paragraphs))
		for _, paragraph := range p.Paragraphs {
			paragraph = strings.TrimSpace(paragraph)
			if paragraph != "" {
				paragraphs = append(paragraphs, paragraph)
			}
			if len(paragraphs) == maxPassageParagraphs {
				break
			}
		}
		if len(paragraphs) == 0 {
			continue
		}
		lesson := strings.TrimSpace(p.Lesson)
		if lesson == "" && meta != nil {
			lesson = strings.TrimSpace(meta.Lesson)
		}
		marks := make([]int, 0, len(p.RequiredParagraphs))
		for _, i := range p.RequiredParagraphs {
			if i >= 1 && i <= len(paragraphs) {
				marks = append(marks, i)
			}
		}
		sort.Ints(marks)
		deduped := marks[:0]
		for _, i := range marks {
			if len(deduped) == 0 || deduped[len(deduped)-1] != i {
				deduped = append(deduped, i)
			}
		}
		out = append(out, PassageDraft{
			Title:              title,
			Author:             strings.TrimSpace(p.Author),
			Paragraphs:         paragraphs,
			Lesson:             lesson,
			Required:           strings.TrimSpace(p.Required),
			RequiredParagraphs: deduped,
			Confidence:         clamp01(p.Confidence),
		})
	}
	return out
}

// trimOtherDrafts projects the decoded others onto the display contract:
// an unknown kind decodes to the closest honest label rather than being
// dropped or invented — anything the model did not classify as an
// exercise reads as 课文正文 (the prompt's two-kind contract); an empty
// summary carries nothing to display and is dropped.
func trimOtherDrafts(others []OtherDraft) []OtherDraft {
	out := make([]OtherDraft, 0, len(others))
	for _, o := range others {
		summary := strings.TrimSpace(o.Summary)
		if summary == "" {
			continue
		}
		kind := strings.TrimSpace(o.Kind)
		if kind != OtherKindExercise {
			kind = OtherKindText
		}
		out = append(out, OtherDraft{
			Kind:       kind,
			Summary:    summary,
			Confidence: clamp01(o.Confidence),
		})
	}
	return out
}

// wordDecorationRunes are the typographic marks a printed word list sets
// around its words — ★ key-word marks, asterisks, the ※ reference mark,
// bullets, geometric shapes (Issue #47: a live 4A English list answered
// "★library" because every key word on the page is starred). They are
// layout, not language: none of these can be part of an English word or a
// 词语, so trimming them off the ENDS of word cannot eat a real character.
// The set is curated on purpose — extend it rune by rune, never widen to
// "all symbols": the interpunct · stays out because transliterated names
// carry it INSIDE a word, and hyphens/apostrophes are word characters.
const wordDecorationRunes = "*＊※★☆✩✪✫✬✭✮✯✰✦✧" +
	"•‧◦∘○●◎⊙" +
	"▲△▼▽◇◆□■▣◈◐◑" +
	"♠♣♥♦♪♫"

// trimWordDecorations strips the decoration marks (and the whitespace
// interleaved with them) off both ends of a word: "★ library " reads
// "library", " ※美丽● " reads "美丽". Inner characters are never touched —
// "ice cream" keeps its space, a mark inside a word stays where the model
// put it.
func trimWordDecorations(word string) string {
	return strings.TrimFunc(word, func(r rune) bool {
		return unicode.IsSpace(r) || strings.ContainsRune(wordDecorationRunes, r)
	})
}

// containsHan reports whether s carries at least one Han character — the
// writing system a 语文词语 is made of (Issue #47's chinese guard: pinyin,
// digits and English never qualify; 汉字 does, so 「3D打印」 counts as a
// 词语 while "library" does not).
func containsHan(s string) bool {
	for _, r := range s {
		if unicode.Is(unicode.Han, r) {
			return true
		}
	}
	return false
}

// passageCarriesHan reports whether the passage carries at least one Han
// character in its title or its paragraphs — the passage-side analogue of
// containsHan(word): a Han clause anywhere marks a real 语文 课文 (mixed
// pages may quote an English word inside Chinese prose), so only a passage
// with NO Han at all reads as English text leaked through the mis-selected
// category.
func passageCarriesHan(p PassageDraft) bool {
	if containsHan(p.Title) {
		return true
	}
	for _, paragraph := range p.Paragraphs {
		if containsHan(paragraph) {
			return true
		}
	}
	return false
}

// dropNonHanPassages applies Issue #47's Chinese isolation backstop to the
// Issue #13 passage drafts (Recognize's passages-side twin of the entry-word
// guard): a passage with NO Han character anywhere is English prose that
// leaked through the mis-selected category and is dropped — the same
// disposition as a Han-less entry word. Titles keep their decorations
// verbatim, unlike entry words: a passage is a whole transcribed work, and
// #47's trimming rule is about the word field specifically.
func dropNonHanPassages(passages []PassageDraft) []PassageDraft {
	out := make([]PassageDraft, 0, len(passages))
	for _, p := range passages {
		if passageCarriesHan(p) {
			out = append(out, p)
		}
	}
	return out
}

// sniffImage detects PNG and JPEG from their magic bytes and reports the
// MIME type the vision API expects. Everything else is rejected (ErrNotImage
// upstream): WebP/HEIC/PDF uploads fail fast with a clear reason instead of
// an opaque upstream decode error.
func sniffImage(b []byte) (string, bool) {
	if len(b) >= 8 && b[0] == 0x89 && b[1] == 'P' && b[2] == 'N' && b[3] == 'G' &&
		b[4] == 0x0D && b[5] == 0x0A && b[6] == 0x1A && b[7] == 0x0A {
		return "image/png", true
	}
	if isJPEG(b) {
		return "image/jpeg", true
	}
	return "", false
}

// wordlistReplyJSON is the whole Issue #5 object reply's decode shape.
// It decodes straight into the exported WordlistTextbook/WordlistEntry —
// field-for-field the same wire contract, so one struct per concept. A
// null field and an absent field both decode to "" (the honesty contract
// treats them identically, 待确认), and Textbook is a pointer so a null
// textbook stays distinguishable from an all-empty one at parse time
// (Recognize collapses both to meta == nil). Issue #11 adds Poems/Others
// and Issue #13 adds Passages (the Chinese mixed-page arrays); an
// English reply simply decodes them as nil and Recognize normalizes both
// to empty slices.
type wordlistReplyJSON struct {
	Textbook *WordlistTextbook `json:"textbook"`
	Entries  []WordlistEntry   `json:"entries"`
	Poems    []PoemDraft       `json:"poems"`
	Passages []PassageDraft    `json:"passages"`
	Others   []OtherDraft      `json:"others"`
}

// wordlistEntryPattern extracts the word field of every array entry when the
// array itself cannot be parsed (order preserved; the entry boundaries come
// from the paired word+meaning regex below when possible).
var wordlistEntryPattern = regexp.MustCompile(`"word"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,\s*"meaning"\s*:\s*"((?:[^"\\]|\\.)*)"`)

// parsedWordlist is parseWordlistReply's output — decoded but untrimmed.
type parsedWordlist struct {
	textbook *WordlistTextbook
	entries  []WordlistEntry
	poems    []PoemDraft
	passages []PassageDraft
	others   []OtherDraft
}

// parseWordlistReply leniently extracts the recognition result from a model
// reply (mirror of parseWordsJSON's most-to-least-trusting strategy):
//  1. the Issue #5 object contract: the outermost {...} span (or any {...}
//     from a decoder scan — thinking-model prose or fences still parse) as
//     {"textbook":…,"entries":[…],"poems":[…],"passages":[…],"others":[…]};
//     a textbook-less object is legal, and since Issue #11 a poems-only
//     object is too (a page carrying just a poem answers entries:[]), and
//     since Issue #13 a passages-only object as well;
//  2. the Issue #3 legacy contract: [...] as one JSON array (no meta);
//  3. a regex for paired word+meaning fields (meaning may be empty), in
//     order — the degraded object-less fallback.
func parseWordlistReply(reply string) (parsedWordlist, bool) {
	if start, end := strings.Index(reply, "{"), strings.LastIndex(reply, "}"); start >= 0 && end > start {
		var parsed wordlistReplyJSON
		if err := json.Unmarshal([]byte(reply[start:end+1]), &parsed); err == nil &&
			(parsed.Entries != nil || parsed.Textbook != nil || parsed.Poems != nil || parsed.Passages != nil) {
			return parsedWordlist{
				textbook: parsed.Textbook, entries: parsed.Entries,
				poems: parsed.Poems, passages: parsed.Passages, others: parsed.Others,
			}, true
		}
	}
	for i := 0; i < len(reply); i++ {
		if reply[i] != '{' {
			continue
		}
		var parsed wordlistReplyJSON
		if err := json.NewDecoder(strings.NewReader(reply[i:])).Decode(&parsed); err == nil &&
			(parsed.Entries != nil || parsed.Textbook != nil || parsed.Poems != nil || parsed.Passages != nil) {
			return parsedWordlist{
				textbook: parsed.Textbook, entries: parsed.Entries,
				poems: parsed.Poems, passages: parsed.Passages, others: parsed.Others,
			}, true
		}
	}
	if entries, ok := parseWordlistLegacyArray(reply); ok {
		return parsedWordlist{entries: entries}, true
	}
	if matches := wordlistEntryPattern.FindAllStringSubmatch(reply, -1); len(matches) > 0 {
		entries := make([]WordlistEntry, 0, len(matches))
		for _, m := range matches {
			word, werr := strconv.Unquote(`"` + m[1] + `"`)
			meaning, merr := strconv.Unquote(`"` + m[2] + `"`)
			if werr != nil || merr != nil {
				continue
			}
			entries = append(entries, WordlistEntry{Word: word, Meaning: meaning, Confidence: 0.5})
		}
		if len(entries) > 0 {
			return parsedWordlist{entries: entries}, true
		}
	}
	return parsedWordlist{}, false
}

// parseWordlistLegacyArray is the Issue #3 contract: a bare [...] array of
// entries, extracted with the same two-span then scan-from-every-'['
// strategy the original parseWordlistJSON used.
func parseWordlistLegacyArray(reply string) ([]WordlistEntry, bool) {
	start := strings.Index(reply, "[")
	end := strings.LastIndex(reply, "]")
	if start >= 0 && end > start {
		var parsed []WordlistEntry
		if err := json.Unmarshal([]byte(reply[start:end+1]), &parsed); err == nil && parsed != nil {
			return parsed, true
		}
	}
	for i := 0; i < len(reply); i++ {
		if reply[i] != '[' {
			continue
		}
		var parsed []WordlistEntry
		if err := json.NewDecoder(strings.NewReader(reply[i:])).Decode(&parsed); err == nil && parsed != nil {
			return parsed, true
		}
	}
	return nil, false
}
